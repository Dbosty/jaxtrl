"""Offline (non-DAgger) classifier baseline: trains the same MLP classifier
as dagger.py, but on a single FIXED dataset collected once upfront by
rolling out the already-trained frozen pursuer/evader levels directly
against each other -- no classifier in the loop during data collection --
rather than DAgger's iterative "roll out the current classifier, relabel,
retrain" loop (envs/pgj/dagger.py, Algorithm 4).

This is the "offline"/predetermined-trajectory baseline proposed as an
alternative to DAgger: it shows what happens when the classifier only ever
sees states generated by the *true* pursuer levels, never the states its
own (possibly wrong) predictions lead it into. At deployment the classifier
drives its own rollout (via the same LKSPPolicy/TeamPursuerAgent mechanism
as dagger.py/lksp.py), so any state its own mistakes create that wasn't in
the offline dataset is out-of-distribution for it -- unlike DAgger, which
trains on exactly those states by construction.

Dataset: rolls out every (pursuer level, evader level) combination in
{0,...,K} x {1,...,K} -- the same coverage principle Figure 7's D uses --
labeled with the true evader level, collected once, no classifier involved.

Requires envs/pgj/level_k.py's checkpoints (K+1 pursuer levels, K evader
levels) to already exist.

Run with, e.g.:
    python envs/pgj/offline_classifier.py env_var=dummy level_k.K=4 \\
        level_k.checkpoint_dir=checkpoints/level_k
"""

import logging

import gymnasium as gym
import _compat  # noqa: F401
import hydra
import jax
import jax.numpy as jnp
import numpy as np
import torch as th
import torch.nn.functional as F
from omegaconf import OmegaConf

from pgj.env import ODEnv
from pgj.jaxtrl.agent import IndEvader, IndTeamHlp, IndTeamLlp
from pgj.jaxtrl.reward import SparseEvader, SparsePursuer
from pgj.jaxtrl.term import is_terminated

from jaxtrl.rl.ppo.actor.discrete_mlp import DiscreteMLP
from jaxtrl.sim import Sim
from jaxtrl.sim.collect import collect_factory
from jaxtrl.sim.policy import PolicyAggregator
from jaxtrl.utils.logger import ExtWandbLogger

from level_k import EDR, HLP, LLP, SIM_MAX_STEPS, CsvMetricsWriter, save_actor
from pap import UniformLevelKEvaderPolicy, load_evader_levels
from lksp import LKSPPolicy, TeamPursuerAgent, load_pursuer_levels

log = logging.getLogger(__name__)


def collect_offline_dataset(cfg, env, pursuer_levels, evader_levels, key):
    """Rolls out every (pursuer level, evader level) combination directly
    -- true frozen policies on both sides, no classifier involved -- and
    returns the pooled (obs, label) arrays. label = evader level - 1
    (0-indexed, matching the classifier's Discrete(K) output)."""
    K = len(evader_levels)
    all_obs, all_labels = [], []

    for p_idx in range(K + 1):
        llp_p, hlp_p = pursuer_levels[p_idx]
        for level in range(1, K + 1):
            agents = [
                IndTeamLlp(LLP, HLP, EDR, SIM_MAX_STEPS, env.grid.shape),
                IndTeamHlp(LLP, HLP, EDR, SIM_MAX_STEPS, env.grid.shape),
                IndEvader(EDR, LLP, HLP, SIM_MAX_STEPS, env.grid.shape),
            ]
            reward = [
                SparsePursuer(LLP, HLP, EDR, 1, 0),
                SparsePursuer(LLP, HLP, EDR, 1, 0),
                SparseEvader(EDR, LLP, HLP, 1, 0),
            ]
            policy = PolicyAggregator([llp_p, hlp_p, evader_levels[level - 1]])

            sim = Sim(env, agents, reward, is_terminated, max_steps=SIM_MAX_STEPS)
            collect = jax.jit(
                collect_factory(
                    sim.reset, sim.step, policy,
                    timesteps_per_env=cfg.offline.dataset_timesteps_per_env,
                    num_envs=cfg.offline.dataset_num_envs,
                    extended_transition=False,
                )
            )
            key, policy_key, collect_key = jax.random.split(key, 3)
            policy_context = policy.init_context(policy_key)
            transitions = collect(collect_key, policy_context)
            jax.clear_caches()

            obs = np.array(transitions.obs[0])  # team-shared obs, index 0
            labels = np.full((obs.shape[0],), level - 1, dtype=np.int64)
            all_obs.append(obs)
            all_labels.append(labels)

            log.info(
                f"offline dataset: pursuer L{p_idx} vs evader L{level} "
                f"collected ({obs.shape[0]} samples)"
            )

    return np.concatenate(all_obs), np.concatenate(all_labels), key


def train_classifier_step(classifier, optimizer, obs_batch, label_batch, device):
    obs_t = th.as_tensor(obs_batch, dtype=th.float32, device=device)
    label_t = th.as_tensor(label_batch, dtype=th.long, device=device)

    logits = classifier.trl_actor_net(obs_t)
    loss = F.cross_entropy(logits, label_t)

    optimizer.zero_grad()
    loss.backward()
    optimizer.step()

    acc = (logits.argmax(dim=-1) == label_t).float().mean().item()
    return loss.item(), acc


def eval_winrate(cfg, env, classifier, pursuer_levels, evader_levels, key):
    team_agent = TeamPursuerAgent(LLP, HLP, EDR, SIM_MAX_STEPS, env.grid.shape)
    edr_agent = IndEvader(EDR, LLP, HLP, SIM_MAX_STEPS, env.grid.shape)
    agents = [team_agent, edr_agent]
    reward = [SparsePursuer(LLP, HLP, EDR, 1, 0), SparseEvader(EDR, LLP, HLP, 1, 0)]
    policy = PolicyAggregator([
        LKSPPolicy(classifier, pursuer_levels[1:]),
        UniformLevelKEvaderPolicy(evader_levels),
    ])

    sim = Sim(env, agents, reward, is_terminated, max_steps=SIM_MAX_STEPS)
    collect = jax.jit(
        collect_factory(
            sim.reset, sim.step, policy,
            timesteps_per_env=cfg.offline.dataset_timesteps_per_env,
            num_envs=cfg.offline.eval_num_envs,
            extended_transition=True,
        )
    )
    key, policy_key, collect_key = jax.random.split(key, 3)
    policy_context = policy.init_context(policy_key)
    transitions = collect(collect_key, policy_context)
    jax.clear_caches()

    winrate = float(
        jnp.sum(transitions.raw_next_obs.state.agent_win[..., LLP])
        / jnp.sum(transitions.terminated)
    )
    return winrate, key


@hydra.main(version_base=None, config_path="../../conf", config_name="offline_classifier")
def main(cfg):
    if cfg.seed is None:
        cfg.seed = np.random.randint(0, 2**32 - 1)

    key = jax.random.key(cfg.seed)
    key, seed_key = jax.random.split(key)
    np_seed, th_seed = jax.random.randint(seed_key, (2,), 0, 2**16 - 1)
    np.random.seed(int(np_seed))
    th.manual_seed(int(th_seed))
    rng = np.random.default_rng(int(np_seed))

    env = ODEnv()

    key, pk, ek = jax.random.split(key, 3)
    pursuer_levels = load_pursuer_levels(cfg, env, pk)
    evader_levels = load_evader_levels(cfg, env, ek)

    log.info("collecting offline dataset (no classifier involved)...")
    key, dataset_key = jax.random.split(key)
    obs_data, label_data, key = collect_offline_dataset(cfg, env, pursuer_levels, evader_levels, dataset_key)
    log.info(f"offline dataset: {obs_data.shape[0]} total samples")

    key, classifier_key = jax.random.split(key)
    team_agent = TeamPursuerAgent(LLP, HLP, EDR, SIM_MAX_STEPS, env.grid.shape)
    classifier = DiscreteMLP(
        team_agent.pi_obs_spec, gym.spaces.Discrete(cfg.level_k.K), classifier_key,
        net_arch=list(cfg.classifier.net_arch),
        activation_func=cfg.classifier.activation_func,
        device=cfg.device,
    )
    optimizer = th.optim.Adam(classifier.trl_actor_net.parameters(), lr=cfg.offline.lr)

    exp_name = cfg.get("exp_name") or "pgj_offline_classifier"
    logger = ExtWandbLogger(
        exp_name=exp_name,
        config=OmegaConf.to_container(cfg, resolve=True),
        **{**cfg.env_var.wandb, "sync_tensorboard": False, "offline": False},
    )
    metrics_dir = cfg.get("metrics_dir", "metrics")
    csv_writer = CsvMetricsWriter(f"{metrics_dir}/{exp_name}.csv")

    n = obs_data.shape[0]
    cumulative_samples = 0
    for epoch in range(1, cfg.offline.epochs + 1):
        perm = rng.permutation(n)
        losses, accs = [], []
        for start in range(0, n, cfg.offline.batch_size):
            idx = perm[start : start + cfg.offline.batch_size]
            loss, acc = train_classifier_step(
                classifier, optimizer, obs_data[idx], label_data[idx], cfg.device
            )
            losses.append(loss)
            accs.append(acc)
        cumulative_samples += n

        log_dict = {
            "train/loss": float(np.mean(losses)),
            "train/accuracy": float(np.mean(accs)),
        }

        # always eval on epoch 1 so the CSV header locks in this column from
        # the start -- CsvMetricsWriter silently drops any key introduced
        # after the first row, since the header is fixed on first write.
        if epoch == 1 or epoch % cfg.offline.eval_every == 0 or epoch == cfg.offline.epochs:
            key, eval_key = jax.random.split(key)
            winrate, key = eval_winrate(cfg, env, classifier, pursuer_levels, evader_levels, eval_key)
            log_dict["rollout/pursuer_winrate"] = winrate
            log.info(
                f"epoch {epoch}: loss={log_dict['train/loss']:.4f} "
                f"acc={log_dict['train/accuracy']:.4f} winrate={winrate:.4f}"
            )
        else:
            log.info(
                f"epoch {epoch}: loss={log_dict['train/loss']:.4f} "
                f"acc={log_dict['train/accuracy']:.4f}"
            )

        logger.log_scalars(log_dict, timestep=cumulative_samples)
        csv_writer.log(cumulative_samples, log_dict)

    csv_writer.close()
    save_actor(classifier, f"{cfg.offline.checkpoint_dir}/offline_classifier.pt")


if __name__ == "__main__":
    main()
