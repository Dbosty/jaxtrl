"""Algorithm 2 (APEGS paper): Primitive Action Policy (PAP).

Section 4.2: "Using the K levels of Evader policies generated by Algorithm 1,
we train the Primitive Action Policy, pi_PAP, by solving a POMDP which is
the same as the one solved in training pursuer policies in Algorithm 1, but
now with additional randomization over K levels of Evader."

So training PAP is exactly envs/pgj/level_k.py's train_pursuer_stage, with
the fixed/perturbed single-level evader opponent swapped for one that
resamples a random trained evader level every episode. Section 5.3 specifies
the sampled range as "levels 1 to K" (excluding the level-0 mixture), which
is what UniformLevelKEvaderPolicy below does.

Algorithm 2's *execution* loop ("sample obs, act via pi_PAP, step") is just
the ordinary Sim/collect rollout used everywhere else in this repo -- there
is nothing new to implement there.

Requires envs/pgj/level_k.py to have already been run (with the same
level_k.checkpoint_dir / K / train.actor), so evader_L1.pt..evader_LK.pt
exist to train against.

Run with, e.g.:
    python envs/pgj/pap.py env_var=dummy level_k.K=4 \\
        level_k.checkpoint_dir=checkpoints/level_k
"""

import _compat  # noqa: F401
import hydra
import jax
import jax.numpy as jnp
import numpy as np
import torch as th

from pgj.env import ODEnv
from pgj.jaxtrl.agent import IndEvader

from jaxtrl.rl.ppo.trainer import ACTOR_MAP
from jaxtrl.sim.policy import Policy

from level_k import EDR, HLP, LLP, SIM_MAX_STEPS, save_actor, train_pursuer_stage


class UniformLevelKEvaderPolicy(Policy):
    """Opponent used to train PAP and LKSP: resamples, once per episode,
    which frozen trained evader level (1..K, from envs/pgj/level_k.py) to
    play against for the rest of that episode -- Section 5.3's "evader
    policy randomly selected between levels 1 to K".

    All len(levels) candidates are evaluated every step (rather than only
    the selected one) purely so this stays jit-friendly: which one is
    "selected" is a traced value inside jax.jit, so the selection has to be
    an array index/gather, not a Python-level branch.
    """

    def __init__(self, levels: list[Policy]):
        assert len(levels) > 0, "need at least one evader level to sample from"
        self.levels = levels

    def _select(self, key):
        return jax.random.randint(key, (), 0, len(self.levels))

    def init_context(self, key):
        key, sel_key = jax.random.split(key)
        return {
            "idx": self._select(sel_key),
            "ctxs": [lvl.init_context(key) for lvl in self.levels],
        }

    def reset_context(self, context, key):
        key, sel_key = jax.random.split(key)
        return {
            "idx": self._select(sel_key),
            "ctxs": [
                lvl.reset_context(ctx, key)
                for lvl, ctx in zip(self.levels, context["ctxs"])
            ],
        }

    def __call__(self, obs_for_pi, context, key):
        outs = [
            lvl(obs_for_pi, ctx, key) for lvl, ctx in zip(self.levels, context["ctxs"])
        ]
        actions = jnp.stack([out[0] for out in outs])
        action = actions[context["idx"]]
        return action, {"idx": context["idx"], "ctxs": [out[1] for out in outs]}


def load_evader_levels(cfg, env, key):
    """Load the K trained IndEvader actors (levels 1..K) saved by
    envs/pgj/level_k.py. Architecture must match cfg.train (actor type +
    actor_kwargs), since we're reconstructing the network before loading its
    state_dict."""
    spec = IndEvader(EDR, LLP, HLP, SIM_MAX_STEPS, env.grid.shape)

    levels = []
    for i in range(1, cfg.level_k.K + 1):
        key, actor_key = jax.random.split(key)
        actor = ACTOR_MAP[cfg.train.actor](
            spec.pi_obs_spec,
            spec.pi_action_spec,
            actor_key,
            **{**cfg.train.get("actor_kwargs", {}), "device": cfg.device},
        )
        path = f"{cfg.level_k.checkpoint_dir}/evader_L{i}.pt"
        actor.trl_actor.load_state_dict(th.load(path, map_location=cfg.device))
        levels.append(actor)
    return levels


@hydra.main(version_base=None, config_path="../../conf", config_name="pap")
def main(cfg):
    if cfg.seed is None:
        cfg.seed = np.random.randint(0, 2**32 - 1)

    key = jax.random.key(cfg.seed)
    key, seed_key = jax.random.split(key)

    np_seed, th_seed = jax.random.randint(seed_key, (2,), 0, 2**16 - 1)
    np.random.seed(int(np_seed))
    th.manual_seed(int(th_seed))

    env = ODEnv()

    key, load_key = jax.random.split(key)
    evader_levels = load_evader_levels(cfg, env, load_key)
    evader_policy = UniformLevelKEvaderPolicy(evader_levels)

    llp_path = f"{cfg.pap.checkpoint_dir}/pap_llp.pt"
    hlp_path = f"{cfg.pap.checkpoint_dir}/pap_hlp.pt"

    key, stage_key = jax.random.split(key)
    llp, hlp = train_pursuer_stage(
        cfg,
        env,
        IndEvader(EDR, LLP, HLP, SIM_MAX_STEPS, env.grid.shape),
        evader_policy,
        stage_key,
        cfg.get("exp_name") or "pgj_pap",
        llp_path,
        hlp_path,
    )

    save_actor(llp, llp_path)
    save_actor(hlp, hlp_path)


if __name__ == "__main__":
    main()
